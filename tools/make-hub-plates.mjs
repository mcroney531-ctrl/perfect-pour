// Generates the provisional hub plates from js/hub-scenes.js, so the marked
// anchors always match the ones the hotspots use. These are art templates,
// not art: each one is labelled on its face and in the app.
//   node tools/make-hub-plates.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ctx = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(ROOT, 'js/hub-scenes.js'), 'utf8'), ctx);
const { SCENES } = ctx.RiversideHubScenes;

const LABEL = { pilsner: '1  PILSNER TAP', hefeweizen: '2  HEFEWEIZEN TAP', stout: '3  NITRO STOUT TAP', finalRush: '4  FINAL RUSH MEDALLION' };

function plate(name, sc) {
  const { width: W, height: H } = sc;
  const A = Object.fromEntries(Object.entries(sc.stations).map(([id, st]) => [id, st.at]));
  const k = Math.min(W / 1170, H / 1200);               // text and stroke scale
  const f = n => (n * k).toFixed(1);
  const p = A.pilsner, h = A.hefeweizen, s = A.stout, r = A.finalRush;
  // A U-shaped counter seen from its open end: back run through the Hefeweizen
  // tap, arms through the Pilsner and Stout taps, widening toward the viewer.
  const backY = h[1], backL = p[0] - (s[0] - p[0]) * 0.1, backR = s[0] + (s[0] - p[0]) * 0.1;
  const leftAt = y => backL - (y - backY) * ((backL - (p[0] - (s[0] - p[0]) * 0.28)) / Math.max(1, p[1] - backY));
  const rightAt = y => W - leftAt(y);
  const depth = 120 * k;
  const counter = `M${leftAt(H).toFixed(0)} ${H} L${backL.toFixed(0)} ${backY} L${backR.toFixed(0)} ${backY} L${rightAt(H).toFixed(0)} ${H}`;
  const inner = `M${(leftAt(H) + depth * 2.4).toFixed(0)} ${H} L${(backL + depth).toFixed(0)} ${(backY + depth * 0.5).toFixed(0)} L${(backR - depth).toFixed(0)} ${(backY + depth * 0.5).toFixed(0)} L${(rightAt(H) - depth * 2.4).toFixed(0)} ${H}`;
  const marker = (id, [x, y]) => `
    <g>
      <ellipse cx="${x}" cy="${y}" rx="${f(70)}" ry="${f(20)}" fill="none" stroke="#5fcf8a" stroke-width="${f(3)}" stroke-dasharray="${f(10)} ${f(8)}"/>
      <path d="M${x - 30 * k} ${y}H${x + 30 * k}M${x} ${y - 30 * k}V${y + 30 * k}" stroke="#5fcf8a" stroke-width="${f(2)}"/>
      <text x="${x}" y="${y + 58 * k}" text-anchor="middle" font-size="${f(26)}" fill="#5fcf8a">${LABEL[id]}</text>
      <text x="${x}" y="${y + 90 * k}" text-anchor="middle" font-size="${f(20)}" fill="#8fbfa3">(${x}, ${y})</text>
    </g>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" font-family="Arial, Helvetica, sans-serif" font-weight="700">
  <!-- PROVISIONAL hub plate (${name}), generated by tools/make-hub-plates.mjs from js/hub-scenes.js.
       Not production art: it marks where the real plate's stations must sit. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#151b1d"/><stop offset="0.55" stop-color="#10171a"/><stop offset="1" stop-color="#0b1412"/>
    </linearGradient>
    <radialGradient id="pool" cx="0.5" cy="${(backY / H).toFixed(3)}" r="0.6">
      <stop offset="0" stop-color="#ffb547" stop-opacity="0.16"/><stop offset="1" stop-color="#ffb547" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#bg)"/>
  <rect width="${W}" height="${H}" fill="url(#pool)"/>
  <!-- Composition guide: back wall / sign area, U-shaped counter, centre aisle. -->
  <rect x="${f(60)}" y="${(backY * 0.42).toFixed(0)}" width="${W - 120 * k}" height="${(backY * 0.45).toFixed(0)}" fill="none" stroke="#2d6553" stroke-width="${f(2)}" stroke-dasharray="${f(14)} ${f(10)}"/>
  <text x="${W / 2}" y="${(backY * 0.42 + 44 * k).toFixed(0)}" text-anchor="middle" font-size="${f(26)}" fill="#4f8f78">BACK WALL · RIVERSIDE SIGN · TANKS · PENDANTS</text>
  <path d="${counter}" fill="none" stroke="#b9733f" stroke-width="${f(4)}" stroke-opacity="0.7"/>
  <path d="${inner}" fill="none" stroke="#b9733f" stroke-width="${f(2)}" stroke-opacity="0.45" stroke-dasharray="${f(12)} ${f(10)}"/>
  <text x="${W / 2}" y="${((p[1] + r[1]) / 2).toFixed(0)}" text-anchor="middle" font-size="${f(22)}" fill="#8a6a4e">CENTRE AISLE</text>
  ${Object.entries(A).map(([id, pt]) => marker(id, pt)).join('')}
  <text x="${W / 2}" y="${(H * 0.5).toFixed(0)}" text-anchor="middle" font-size="${f(64)}" fill="#ffffff" fill-opacity="0.07"
        transform="rotate(-${name === 'portrait' ? 60 : 18} ${W / 2} ${(H * 0.5).toFixed(0)})">PROVISIONAL · NOT FINAL ART</text>
  <text x="${f(30)}" y="${H - 24 * k}" font-size="${f(18)}" fill="#ffffff" fill-opacity="0.45">PROVISIONAL HUB PLATE · ${name.toUpperCase()} ${W}×${H} · replace with the Riverside ${name} hub art</text>
</svg>
`;
}

fs.mkdirSync(path.join(ROOT, 'assets/hub'), { recursive: true });
for (const [name, sc] of Object.entries(SCENES)) {
  if (!sc.provisional) continue;            // real art in place for this composition
  const out = path.join(ROOT, sc.src);
  fs.writeFileSync(out, plate(name, sc));
  console.log('wrote', path.relative(ROOT, out));
}
